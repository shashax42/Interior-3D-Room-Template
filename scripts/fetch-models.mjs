// Downloads CC0 photoscanned furniture from Poly Haven, shrinks the textures, packs each model into one GLB,
// and writes it as base64 JSON under public/models (the hosted link only serves standard web file types).
// Also writes src/furniture/scanned.ts with each model's real size.
//
//   node scripts/fetch-models.mjs

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { NodeIO } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import { getBounds } from '@gltf-transform/functions'

const MODELS = [
  { id: 'ArmChair_01', name: '클래식 암체어', mount: 'floor' },
  { id: 'Sofa_01', name: '클래식 소파', mount: 'floor', top: 0.45 },
  { id: 'ClassicConsole_01', name: '조각 콘솔', mount: 'floor' },
  { id: 'ClassicNightstand_01', name: '클래식 협탁', mount: 'floor' },
  { id: 'Chandelier_01', name: '갓 샹들리에', mount: 'ceiling' },
  { id: 'Chandelier_03', name: '캔들 샹들리에', mount: 'ceiling' },
  { id: 'fancy_picture_frame_01', name: '풍경화 액자', mount: 'wall' },
  { id: 'fancy_picture_frame_02', name: '금장 액자', mount: 'wall' },
  { id: 'antique_ceramic_vase_01', name: '도자기 화병', mount: 'floor', small: true },
  { id: 'mantel_clock_01', name: '앤티크 탁상시계', mount: 'floor', small: true },
]

const TMP = 'node_modules/.cache/polyhaven'
const OUT = 'public/models'
rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

async function download(url, path) {
  const r = await fetch(url)
  if (!r.ok) throw new Error(`${r.status} ${url}`)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, Buffer.from(await r.arrayBuffer()))
}

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS)
const entries = []

for (const m of MODELS) {
  const files = await (await fetch(`https://api.polyhaven.com/files/${m.id}`)).json()
  const gltf = files.gltf['1k'].gltf
  const dir = join(TMP, m.id)
  rmSync(dir, { recursive: true, force: true })
  const main = join(dir, `${m.id}.gltf`)
  await download(gltf.url, main)
  for (const [rel, f] of Object.entries(gltf.include ?? {})) await download(f.url, join(dir, rel))

  const resized = join(dir, `${m.id}.resized.glb`)
  const glb = join(dir, `${m.id}.glb`)
  // Textures at 512 px are plenty at room scale; meshopt compression shrinks the geometry several times over.
  execFileSync('npx', ['gltf-transform', 'resize', main, resized, '--width', '512', '--height', '512'], { stdio: 'ignore' })
  execFileSync('npx', ['gltf-transform', 'meshopt', resized, glb], { stdio: 'ignore' })

  const doc = await io.read(resized)
  const b = getBounds(doc.getRoot().listScenes()[0])
  const r2 = (v) => Math.round(v * 100) / 100
  const size = { w: r2(b.max[0] - b.min[0]), d: r2(b.max[2] - b.min[2]), h: r2(b.max[1] - b.min[1]) }

  // Catalog thumbnail
  const thumb = join(OUT, 'thumbs', `${m.id}.jpg`)
  await download(`https://cdn.polyhaven.com/asset_img/thumbs/${m.id}.png?width=160&height=160`, join(dir, 'thumb.png'))
  mkdirSync(join(OUT, 'thumbs'), { recursive: true })
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '80', join(dir, 'thumb.png'), '--out', thumb], { stdio: 'ignore' })

  const bytes = readFileSync(glb)
  writeFileSync(join(OUT, `${m.id}.json`), JSON.stringify({ source: `https://polyhaven.com/a/${m.id} (CC0)`, data: bytes.toString('base64') }))
  entries.push({ ...m, size })
  console.log(`${m.id}: ${(bytes.length / 1024).toFixed(0)} KB`, size)
}

const ts = `// Generated by scripts/fetch-models.mjs — photoscanned CC0 models from Poly Haven, sizes in meters.

export type ScannedModel = {
  id: string
  name: string
  mount: 'floor' | 'wall' | 'ceiling'
  size: { w: number; d: number; h: number }
  small?: boolean
  top?: number
}

export const SCANNED: ScannedModel[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync('src/furniture/scanned.ts', ts)
